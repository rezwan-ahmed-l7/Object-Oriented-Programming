#include <iostream>
#include <cmath>
using namespace std;

int main() {
    cout << "sin(0): " << sin(0) << endl;
    cout << "cos(0): " << cos(0) << endl;
    cout << "tan(0): " << tan(0) << endl;
    cout << "sqrt(16): " << sqrt(16) << endl;
    cout << "pow(2, 3): " << pow(2, 3) << endl;

    return 0;
}